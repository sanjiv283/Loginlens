# LoginLens - run with: Rscript -e 'shiny::runApp(".")'
suppressPackageStartupMessages({ library(shiny); library(ggplot2); library(dplyr); library(lubridate); library(DT) })
app_dir <- "."
for (f in c("generate_data", "detector", "evaluate")) source(file.path(app_dir, "R", paste0(f, ".R")), local = FALSE)

DATA_PATH <- file.path(app_dir, "data", "login_events.csv")
if (!file.exists(DATA_PATH)) write_login_data(DATA_PATH)
EVENTS   <- read_login_data(DATA_PATH)
BASE_FIT <- fit_baseline(EVENTS[EVENTS$period == "baseline", ])           # baseline period only
FEAT     <- compute_features(EVENTS, BASE_FIT)                            # labels are dropped inside
FEAT     <- cbind(FEAT[, setdiff(names(FEAT), c("event_id", "user_id", "timestamp", "status"))],
                  EVENTS[, c("event_id", "user_id", "timestamp", "status", "device", "location", "period")])
EVAL_IDX <- EVENTS$period == "evaluation"
TRUTH    <- EVENTS$is_injected_anomaly[EVAL_IDX]                          # used only for evaluation
PROFILES <- threshold_profiles()
metric_cols <- c("precision", "recall", "fpr", "accuracy")
fmt <- function(x) ifelse(is.na(x), "NA", sprintf("%.3f", x))

disclaimer <- div(class = "alert alert-warning",
  strong("Synthetic data only."), " Every login, user, device and location here is fictional and was generated by ",
  code("R/generate_data.R"), ". Flags mean 'statistically unusual', not 'confirmed attack'.")

ui <- fluidPage(
  titlePanel("LoginLens - Statistical Detection of Unusual Login Activity"),
  selectInput("profile", "Threshold profile (Overview & Explorer)", names(PROFILES), "balanced"),
  tabsetPanel(
    tabPanel("Overview", br(), disclaimer,
      fluidRow(lapply(c("n_events", "n_users", "n_flagged", "pct_flagged"), function(id)
        column(3, wellPanel(h4(textOutput(paste0(id, "_label"), inline = TRUE)), h2(textOutput(id)))))),
      plotOutput("p_time", height = 260),
      fluidRow(column(6, plotOutput("p_hour", height = 260)), column(6, plotOutput("p_flag", height = 260)))),
    tabPanel("Login Explorer", br(),
      fluidRow(
        column(3, selectizeInput("f_user", "User", sort(unique(EVENTS$user_id)), multiple = TRUE)),
        column(3, dateRangeInput("f_date", "Date", min(as.Date(EVENTS$timestamp[EVAL_IDX])),
                                 max(as.Date(EVENTS$timestamp[EVAL_IDX])),
                                 min(as.Date(EVENTS$timestamp[EVAL_IDX])), max(as.Date(EVENTS$timestamp[EVAL_IDX])))),
        column(2, selectizeInput("f_status", "Status", c("success", "failure"), multiple = TRUE)),
        column(2, selectInput("f_flag", "Anomaly flag", c("all", "flagged", "normal"))),
        column(2, textInput("f_search", "Search", ""))),
      downloadButton("dl", "Export filtered CSV"), br(), br(), DTOutput("tbl")),
    tabPanel("Threshold Lab", br(), disclaimer,
      p("Ground-truth labels (injected anomalies) are used here only to score the detector after the fact."),
      h4("Custom profile"),
      fluidRow(
        column(4, sliderInput("c_hour", "Hour rarity ratio (flag if P(hour) < ratio/24)", 0.05, 0.6, 0.2, 0.01)),
        column(4, sliderInput("c_z", "Daily-count z threshold", 1.5, 5, 3, 0.1)),
        column(4, sliderInput("c_burst", "Failed-login burst size", 2, 10, 4, 1))),
      tableOutput("lab_tbl"), plotOutput("lab_plot", height = 320)),
    tabPanel("Statistical Insights", br(), uiOutput("insights"))))

server <- function(input, output, session) {
  scored <- reactive(apply_thresholds(FEAT, PROFILES[[input$profile]]))
  ev_scored <- reactive(scored()[EVAL_IDX, ])

  stats <- reactive({ d <- ev_scored()
    list(n_events = nrow(d), n_users = length(unique(d$user_id)), n_flagged = sum(d$flag),
         pct_flagged = if (nrow(d)) sprintf("%.1f%%", 100 * mean(d$flag)) else "NA") })
  labels <- c(n_events = "Total events", n_users = "Users", n_flagged = "Flagged events", pct_flagged = "Flag percentage")
  for (id in names(labels)) local({ i <- id
    output[[paste0(i, "_label")]] <- renderText(labels[[i]])
    output[[i]] <- renderText(as.character(stats()[[i]])) })

  output$p_time <- renderPlot({ d <- ev_scored(); req(nrow(d) > 0)
    d$date <- as.Date(d$timestamp); d$kind <- ifelse(d$flag, "flagged", "normal")
    ggplot(d, aes(date, fill = kind)) + geom_bar() + scale_fill_manual(values = c(normal = "grey60", flagged = "firebrick")) +
      labs(title = "Login activity per day (evaluation period)", x = NULL, y = "Events", fill = NULL) + theme_minimal() })
  output$p_hour <- renderPlot({ d <- ev_scored(); req(nrow(d) > 0)
    ggplot(d, aes(login_hour)) + geom_histogram(binwidth = 1, boundary = -0.5, fill = "steelblue") +
      labs(title = "Login-hour distribution", x = "Hour of day (UTC)", y = "Events") + theme_minimal() })
  output$p_flag <- renderPlot({ d <- ev_scored(); req(nrow(d) > 0)
    d$kind <- ifelse(d$flag, "flagged", "normal")
    ggplot(d, aes(kind, fill = kind)) + geom_bar(show.legend = FALSE) +
      scale_fill_manual(values = c(normal = "grey60", flagged = "firebrick")) +
      labs(title = "Normal vs flagged", x = NULL, y = "Events") + theme_minimal() })

  filtered <- reactive(filter_events(ev_scored(), input$f_user, input$f_date, input$f_status, input$f_flag, input$f_search))
  show_cols <- c("timestamp", "user_id", "status", "device", "location", "anomaly_score", "flag", "reason")
  output$tbl <- renderDT({ d <- filtered()[, show_cols]; d$anomaly_score <- round(d$anomaly_score, 2)
    datatable(d, rownames = FALSE, options = list(pageLength = 15)) })
  output$dl <- downloadHandler(function() "loginlens_filtered.csv",
                               function(file) export_csv(filtered()[, show_cols], file))

  lab <- reactive({
    pr <- c(PROFILES, list(custom = list(hour_ratio = input$c_hour, z = input$c_z, burst = input$c_burst)))
    compare_profiles(FEAT[EVAL_IDX, ], TRUTH, pr) })
  output$lab_tbl <- renderTable({ d <- lab(); for (m in metric_cols) d[[m]] <- fmt(d[[m]]); d }, striped = TRUE)
  output$lab_plot <- renderPlot({
    d <- lab() |> select(profile, all_of(metric_cols)) |>
      tidyr::pivot_longer(-profile, names_to = "metric", values_to = "value")
    ggplot(d, aes(profile, value, fill = metric)) + geom_col(position = "dodge", na.rm = TRUE) +
      scale_y_continuous(limits = c(0, 1)) + labs(title = "Threshold comparison (NA metrics not drawn)", x = NULL, y = NULL) +
      theme_minimal() })

  output$insights <- renderUI(insights_ui(lab()))
}

insights_ui <- function(res) {
  r <- function(p) res[res$profile == p, ]
  tagList(
    h3("What the detector does"),
    p("A baseline period (first 30 days) teaches the detector each user's habits. The evaluation period (next 30 days) is then scored using only those habits plus the same-day / recent-event history. Ground-truth labels never enter the detector."),
    h4("1. Login-hour rarity"),
    p("Counts of logins per hour are smoothed: P(h) = ((K n)_h + a) / (N + 24 a), with a = 0.5 and K a circular Gaussian kernel (sd 1 hour) so 23:00 and 00:00 are neighbours. Surprisal = -log2 P(h). Flag if P(h) < r/24, i.e. the hour is much rarer than a uniform guess. Users with < 20 baseline events use the pooled profile."),
    h4("2. Daily-frequency z-score"),
    p("For the k-th login of a user's day: z = (k - mean) / max(sd, 1), where mean and sd come from the user's baseline daily counts. The floor of 1 prevents division by zero; z is capped at 10. Only past events of that day are used."),
    h4("3. Failed-login bursts"),
    p("Count failures by the same user in the trailing 10 minutes; flag when the count reaches the profile's burst size."),
    h4("4. Combined score"),
    p("score = max(surprisal / surprisal threshold, z / z threshold, burst / burst threshold). Flag when score >= 1; the reason text lists which rules fired."),
    h3("Results on this synthetic dataset"),
    p(sprintf("Balanced profile: precision %s, recall %s, false-positive rate %s. Relaxed: %s / %s / %s. Strict: %s / %s / %s.",
              fmt(r("balanced")$precision), fmt(r("balanced")$recall), fmt(r("balanced")$fpr),
              fmt(r("relaxed")$precision), fmt(r("relaxed")$recall), fmt(r("relaxed")$fpr),
              fmt(r("strict")$precision), fmt(r("strict")$recall), fmt(r("strict")$fpr))),
    p("Lower thresholds raise recall but also false positives here; that trade-off is a property of this data, not a general law."),
    h3("Assumptions and limitations"),
    tags$ul(
      tags$li("Daily login counts are discrete, skewed and over-dispersed, so a z-score (a normal approximation) is only a rough guide; a count model (Poisson / negative binomial) would be more principled."),
      tags$li("Baseline is assumed mostly normal; contamination would inflate normal variability."),
      tags$li("Habits are assumed stable; new jobs, travel or time-zone changes cause false positives."),
      tags$li("Device and location are not used. Data is simulated, so performance numbers are not evidence about real systems."),
      tags$li("A flag means 'unusual', never 'confirmed attack'.")))
}

shinyApp(ui, server)
