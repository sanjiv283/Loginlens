# ── Dark Y2K ggplot theme ─────────────────────────────────────
theme_lens <- function(base_size = 12) {
  bg       <- "#0a0e1a"
  bg_panel <- "#0f1623"
  grid_col <- "rgba(148,163,184,0.08)"
  text_col <- "#94a3b8"
  title_col <- "#cbd5e1"
  theme_minimal(base_size = base_size, base_family = "sans") %+replace%
    theme(
      plot.background      = element_rect(fill = bg, color = NA),
      panel.background     = element_rect(fill = bg_panel, color = NA),
      panel.grid.major     = element_line(color = "#1e293b", linewidth = 0.4),
      panel.grid.minor     = element_blank(),
      axis.text            = element_text(color = text_col, size = 10,
                                          family = "monospace"),
      axis.title           = element_text(color = text_col, size = 11),
      plot.title           = element_text(color = title_col, size = 13,
                                          face = "bold", hjust = 0,
                                          margin = margin(b = 6)),
      plot.subtitle        = element_text(color = text_col, size = 10,
                                          hjust = 0),
      legend.background    = element_rect(fill = bg, color = NA),
      legend.text          = element_text(color = text_col, size = 10),
      legend.title         = element_text(color = text_col, size = 10),
      legend.key           = element_rect(fill = "transparent", color = NA),
      strip.background     = element_rect(fill = "#131c30", color = "#1e293b"),
      strip.text           = element_text(color = text_col, size = 10),
      plot.margin          = margin(12, 16, 12, 16)
    )
}

