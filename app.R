# ── Server (unchanged from original) ─────────────────────────
server <- function(input, output, session) {
  scored    <- reactive(apply_thresholds(FEAT, PROFILES[[input$profile]]))
  ev_scored <- reactive(scored()[EVAL_IDX, ])

  stats <- reactive({
    d <- ev_scored()
    list(n_events   = nrow(d),
         n_users    = length(unique(d$user_id)),
         n_flagged  = sum(d$flag),
         pct_flagged = if (nrow(d)) sprintf("%.1f%%", 100 * mean(d$flag)) else "NA")
  })
  labels <- c(n_events = "Total events", n_users = "Users",
              n_flagged = "Flagged events", pct_flagged = "Flag rate")
  for (id in names(labels)) local({
    i <- id
    output[[paste0(i, "_label")]] <- renderText(labels[[i]])
    output[[i]]                   <- renderText(as.character(stats()[[i]]))
  })

  output$p_time <- renderPlot({
    d <- ev_scored(); req(nrow(d) > 0)
    d$date <- as.Date(d$timestamp)
    d$kind <- ifelse(d$flag, "flagged", "normal")
    ggplot(d, aes(date, fill = kind)) +
      geom_bar() +
      scale_fill_manual(values = PALETTE_FLAG,
                        labels = c(normal = "Normal", flagged = "Flagged")) +
      labs(title = "Login activity per day", x = NULL,
           y = "Events", fill = NULL) +
      theme_lens()
  }, bg = "transparent")

  output$p_hour <- renderPlot({
    d <- ev_scored(); req(nrow(d) > 0)
    ggplot(d, aes(login_hour)) +
      geom_histogram(binwidth = 1, boundary = -0.5,
                     fill = "#2563eb", alpha = 0.8, color = "#1d4ed8") +
      labs(title = "Login-hour distribution",
           x = "Hour of day (UTC)", y = "Events") +
      theme_lens()
  }, bg = "transparent")

  output$p_flag <- renderPlot({
    d <- ev_scored(); req(nrow(d) > 0)
    d$kind <- ifelse(d$flag, "flagged", "normal")
    ggplot(d, aes(kind, fill = kind)) +
      geom_bar(show.legend = FALSE, width = 0.55) +
      scale_fill_manual(values = PALETTE_FLAG) +
      scale_x_discrete(labels = c(normal = "Normal", flagged = "Flagged")) +
      labs(title = "Normal vs flagged events", x = NULL, y = "Events") +
      theme_lens()
  }, bg = "transparent")

  filtered  <- reactive(filter_events(ev_scored(), input$f_user, input$f_date,
                                      input$f_status, input$f_flag, input$f_search))
  show_cols <- c("timestamp", "user_id", "status", "device", "location",
                 "anomaly_score", "flag", "reason")

  output$tbl <- renderDT({
    d <- filtered()[, show_cols]
    d$anomaly_score <- round(d$anomaly_score, 2)
    d$flag <- ifelse(d$flag,
                     '<span class="ll-flag-true">&#9654; Flagged</span>',
                     '<span class="ll-flag-false">Normal</span>')
    datatable(d, rownames = FALSE, escape = FALSE,
              colnames = c("Timestamp", "User", "Status", "Device",
                           "Location", "Score", "Flag", "Detection reason"),
              options = list(
                pageLength = 15,
                scrollX    = TRUE,
                dom        = "lfrtip",
                language   = list(
                  search     = "Search:",
                  lengthMenu = "Show _MENU_ events"
                )
              ),
              class = "cell-border hover")
  })

  output$dl <- downloadHandler(
    filename = function() "loginlens_filtered.csv",
    content  = function(file) export_csv(filtered()[, show_cols], file)
  )

  lab <- reactive({
    pr <- c(PROFILES, list(custom = list(
      hour_ratio = input$c_hour,
      z          = input$c_z,
      burst      = input$c_burst
    )))
    compare_profiles(FEAT[EVAL_IDX, ], TRUTH, pr)
  })

  output$lab_tbl <- renderTable({
    d <- lab()
    for (m in metric_cols) d[[m]] <- fmt(d[[m]])
    d
  }, striped = TRUE, bordered = FALSE, hover = TRUE)

  output$lab_plot <- renderPlot({
    d <- lab() |>
      select(profile, all_of(metric_cols)) |>
      pivot_longer(-profile, names_to = "metric", values_to = "value")
    ggplot(d, aes(profile, value, fill = metric)) +
      geom_col(position = "dodge", na.rm = TRUE, width = 0.65) +
      scale_fill_manual(values = PALETTE_METRIC) +
      scale_y_continuous(limits = c(0, 1)) +
      labs(title = "Threshold comparison (NA metrics not drawn)",
           x = NULL, y = NULL, fill = "Metric") +
      theme_lens()
  }, bg = "transparent")

  output$insights <- renderUI(insights_ui(lab()))
}

# ── Insights UI (unchanged logic, styled wrappers) ────────────
insights_ui <- function(res) {
  r <- function(p) res[res$profile == p, ]
  tagList(
    h3("What the detector does"),
    p("A baseline period (first 30 days) teaches the detector each user\u2019s habits. The evaluation period (next 30 days) is then scored using only those habits plus the same-day / recent-event history. Ground-truth labels never enter the detector."),

    h4("1. Login-hour rarity"),
    p(HTML("Counts of logins per hour are smoothed: <code>P(h) = ((K n)_h + \u03b1) / (N + 24\u03b1)</code>, with \u03b1 = 0.5 and K a circular Gaussian kernel (sd&nbsp;1&nbsp;hour) so 23:00 and 00:00 are neighbours. Surprisal = \u2212log\u2082 P(h). Flag if P(h) &lt; r/24, i.e. the hour is much rarer than a uniform guess. Users with &lt; 20 baseline events use the pooled profile.")),

    h4("2. Daily-frequency z-score"),
    p(HTML("For the k-th login of a user\u2019s day: <code>z = (k \u2212 mean) / max(sd, 1)</code>, where mean and sd come from the user\u2019s baseline daily counts. The floor of 1 prevents division by zero; z is capped at 10. Only past events of that day are used.")),

    h4("3. Failed-login bursts"),
    p("Count failures by the same user in the trailing 10 minutes; flag when the count reaches the profile\u2019s burst size."),

    h4("4. Combined score"),
    p(HTML("score = max(surprisal / surprisal\u2009threshold, z / z\u2009threshold, burst / burst\u2009threshold). Flag when score \u2265 1; the reason text lists which rules fired.")),

    h3("Results on this synthetic dataset"),
    div(class = "ll-insights-results",
      p(sprintf(
        "Balanced profile: precision %s, recall %s, false-positive rate %s. \u2014 Relaxed: %s / %s / %s. \u2014 Strict: %s / %s / %s.",
        fmt(r("balanced")$precision), fmt(r("balanced")$recall), fmt(r("balanced")$fpr),
        fmt(r("relaxed")$precision),  fmt(r("relaxed")$recall),  fmt(r("relaxed")$fpr),
        fmt(r("strict")$precision),   fmt(r("strict")$recall),   fmt(r("strict")$fpr)
      )),
      p("Lower thresholds raise recall but also false positives here; that trade-off is a property of this data, not a general law.")
    ),

    h3("Assumptions and limitations"),
    tags$ul(
      tags$li("Daily login counts are discrete, skewed and over-dispersed, so a z-score (a normal approximation) is only a rough guide; a count model (Poisson / negative binomial) would be more principled."),
      tags$li("Baseline is assumed mostly normal; contamination would inflate normal variability."),
      tags$li("Habits are assumed stable; new jobs, travel or time-zone changes cause false positives."),
      tags$li("Device and location are not used. Data is simulated, so performance numbers are not evidence about real systems."),
      tags$li("A flag means \u2018unusual\u2019, never \u2018confirmed attack\u2019.")
    )
